#!/usr/bin/env node
// kit-ui: fail when UI code styles with anything but the kit's tokens.
// No dependencies.
//
//   node check-literals.mjs <dir|file>... [--lock kit.lock.json] [--strict] [--json]
//
// Errors (exit 1):
//   hex            a hex color in CSS, in a Tailwind arbitrary value, or as a string value
//   color-fn       rgb(), hsl(), oklch() and friends with literal numbers
//   palette        a stock Tailwind palette class (bg-red-500, text-black, ...)
//   base-token     with --lock: a shadcn theme color class (bg-primary, text-muted-foreground,
//                  bg-sidebar-accent, ...) that the kit's theme file does not define. It is left
//                  over from the stock shadcn component and renders with no color.
// Warnings (exit 1 only with --strict):
//   arbitrary      an arbitrary length (w-[13px], gap-[0.3rem], ...)
//
// Skipped: files that carry the "Generated by kit-ui" header (the theme), and with
// --lock, the arbitrary values the kit's own text styles need (text-xs/[19.5px]).
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { dirname, extname, join } from 'node:path';

const args = process.argv.slice(2);
const take = (name) => { const i = args.indexOf(`--${name}`); if (i < 0) return null; const v = args[i + 1]; args.splice(i, 2); return v; };
const flag = (name) => { const i = args.indexOf(`--${name}`); if (i < 0) return false; args.splice(i, 1); return true; };
const lockPath = take('lock'), strict = flag('strict'), asJson = flag('json');
if (!args.length) { console.error('usage: check-literals.mjs <dir|file>... [--lock kit.lock.json] [--strict] [--json]'); process.exit(2); }

const allowed = new Set();
const kitColors = new Set();
if (lockPath) {
  const lock = JSON.parse(readFileSync(lockPath, 'utf8'));
  for (const cls of Object.values(lock.tokens?.text ?? {})) for (const part of String(cls).split(/\s+/)) if (part.includes('[')) allowed.add(part);
  // The kit's color names, to tell a restyled class from one left over from stock shadcn.
  // The lock's paths are relative to the app root, which is where the lock lives.
  const theme = lock.tokens?.file && join(dirname(lockPath), lock.tokens.file);
  if (theme && existsSync(theme)) for (const m of readFileSync(theme, 'utf8').matchAll(/--color-([\w-]+)\s*:/g)) kitColors.add(m[1]);
}

const CODE = new Set(['.ts', '.tsx', '.js', '.jsx', '.mjs', '.css', '.html']);
const SKIP_DIRS = new Set(['node_modules', 'dist', 'build', '.git', '.wrangler', 'coverage', 'test-results', 'playwright-report']);
const files = [];
const walk = (p) => {
  const s = statSync(p);
  if (s.isDirectory()) { for (const name of readdirSync(p)) if (!SKIP_DIRS.has(name)) walk(join(p, name)); }
  else if (CODE.has(extname(p))) files.push(p);
};
for (const a of args) walk(a);

const PALETTE = 'slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose';
const UTIL = 'bg|text|border|ring-offset|ring|fill|stroke|outline|decoration|from|via|to|shadow|divide|accent|caret|placeholder';
// shadcn's theme color names. Flagged only with --lock, and only the ones the kit's theme lacks.
const SHADCN = 'background|foreground|card(?:-foreground)?|popover(?:-foreground)?|primary(?:-foreground)?|secondary(?:-foreground)?|muted(?:-foreground)?|accent(?:-foreground)?|destructive(?:-foreground)?|border|input|ring|chart-[1-5]|sidebar(?:-foreground|-primary(?:-foreground)?|-accent(?:-foreground)?|-border|-ring)?';
const RULES = [
  { rule: 'hex', level: 'error', css: true, re: /#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3,4})\b/g },
  { rule: 'hex', level: 'error', re: /-\[#[0-9a-fA-F]{3,8}\]|(?<!(?:href|to|id|htmlFor|for)=\{?)(['"`])#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3,4})\1/g },
  { rule: 'color-fn', level: 'error', all: true, re: /\b(?:rgba?|hsla?|hwb|oklch|oklab|lab|lch)\(\s*[\d.]/g },
  { rule: 'palette', level: 'error', all: true, re: new RegExp(`(?<![\\w-])(?:${UTIL})-(?:(?:${PALETTE})-\\d{2,3}|black|white)(?![\\w-])`, 'g') },
  { rule: 'base-token', level: 'error', all: true, re: new RegExp(`(?<![\\w-])(?:${UTIL})-(${SHADCN})(?:\\/\\d+)?(?![\\w-])`, 'g') },
  { rule: 'arbitrary', level: 'warning', re: /(?<![\w/-])[a-z][\w-]*-\[-?\d*\.?\d+(?:px|rem|em)\]|[a-z][\w-]*\/\[-?\d*\.?\d+(?:px|rem|em)\]/g },
];

const found = [];
for (const file of files) {
  const src = readFileSync(file, 'utf8');
  if (src.includes('Generated by kit-ui')) continue;
  const isCss = extname(file) === '.css';
  src.split('\n').forEach((line, n) => {
    if (/kit-ui-allow/.test(line)) return;
    for (const r of RULES) {
      if (!r.all && Boolean(r.css) !== isCss) continue;
      for (const m of line.matchAll(r.re)) {
        if (r.rule === 'arbitrary' && allowed.has(m[0])) continue;
        if (r.rule === 'base-token' && (!lockPath || kitColors.has(m[1]))) continue;
        found.push({ file, line: n + 1, level: r.level, rule: r.rule, match: m[0] });
      }
    }
  });
}
const errors = found.filter((f) => f.level === 'error').length;
const warnings = found.length - errors;
if (asJson) console.log(JSON.stringify({ files: files.length, errors, warnings, found }, null, 2));
else {
  for (const f of found) console.log(`${f.file}:${f.line}: ${f.level}: ${f.rule}: ${f.match}`);
  console.log(`${files.length} files, ${errors} errors, ${warnings} warnings`);
}
process.exitCode = errors || (strict && warnings) ? 1 : 0;
